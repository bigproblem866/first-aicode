-- =============================================================================
-- 种子数据：角色 + 角色菜单授权
-- =============================================================================
-- 两个角色：
--   admin     超级管理员，权限串固定为 *:*:*（在 SysPermissionService 里按角色判断，不展开菜单）
--   purchaser 采购员，只授基础资料 + 供应链（库存下只有仓库、采购全部）—— 用来验证"菜单按角色渲染、接口 403"这条链路
--
-- 注意 admin 用户本身不在这里创建：BCrypt 哈希无法可靠地手写进 SQL
-- （网上抄来的哈希一旦不对，现象是"密码明明对却登录失败"，极难排查）。
-- 由 com.erp.system.init.SysDataInitializer 在应用启动时用工程的 BCryptPasswordEncoder 生成。
-- =============================================================================

INSERT INTO `sys_role` (`id`, `role_name`, `role_key`, `role_sort`, `data_scope`, `status`, `remark`, `create_by`)
VALUES (1, '超级管理员', 'admin', 1, '1', '0', '拥有全部权限（权限串 *:*:*）', 'system'),
       (2, '采购员', 'purchaser', 2, '1', '0', '示例角色：只能看基础资料、仓库与采购管理，用于验证权限隔离', 'system')
ON DUPLICATE KEY UPDATE `role_name`  = VALUES(`role_name`),
                        `role_sort`  = VALUES(`role_sort`),
                        `data_scope` = VALUES(`data_scope`),
                        `status`     = VALUES(`status`),
                        `remark`     = VALUES(`remark`);

-- ---------------------------------------------------------------------------
-- 超级管理员：授予全部菜单
-- 用 SELECT 而不是枚举 ID 列表：以后新增菜单会自动被 admin 拿到，
-- 不需要回来改这个文件（否则很容易漏授权，表现为"admin 也点不动新菜单"）。
-- ---------------------------------------------------------------------------
INSERT IGNORE INTO `sys_role_menu` (`role_id`, `menu_id`)
SELECT 1, `id`
FROM `sys_menu`
WHERE `is_deleted` = 0;

-- ---------------------------------------------------------------------------
-- 采购员：只授基础资料 + 供应链（库存下只有仓库，采购全部）
