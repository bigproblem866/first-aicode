-- =============================================================================
-- 菜单「功能分组」
-- -----------------------------------------------------------------------------
-- 只用于前端「功能导航页」的分区展示（参考金蝶：库存调整 / 库存查询 / 报表分析 …），
-- **不参与路由构建、不参与权限判断**。
--
-- 为什么不放在 sys_menu 的 parent_id 里：
--   parent_id 决定的是路由层级与侧边栏结构；分组只是同一目录下的展示归类，
--   两者混在一起会让菜单树变深、路由变复杂，得不偿失。
--
-- 空值表示不分组，前端会回退到用「所属目录名」作为分区标题。
-- =============================================================================

ALTER TABLE `sys_menu`
    ADD COLUMN `group_name` VARCHAR(50) NULL COMMENT '功能分组（功能导航页分区用，不参与路由）'
        AFTER `icon`;
